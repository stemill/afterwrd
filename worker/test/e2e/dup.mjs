// Same-name invite from the page: first a 409 with a confirm; accepting invites anyway.
import puppeteer from "puppeteer-core";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const WORKER = fileURLToPath(new URL("../../", import.meta.url));
const OUT = process.env.OUT ?? fileURLToPath(new URL("./out/", import.meta.url));
const CHROME = process.env.CHROME ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const cli = (...a) => execFileSync("node", ["scripts/invite.mjs", ...a, "--local"], { cwd: WORKER, encoding: "utf8" });
const link = cli("add", `Dup Owner ${Date.now()}`, "--owner").match(/http\S+\/_auth\/invite\/\S+/)[0];
const browser = await puppeteer.launch({ executablePath: CHROME, headless: true });
const page = await browser.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const cdp = await page.createCDPSession(); await cdp.send("WebAuthn.enable");
await cdp.send("WebAuthn.addVirtualAuthenticator", { options: { protocol: "ctap2", transport: "internal", hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
await page.goto(link); await Promise.all([page.waitForNavigation(), page.click("#go")]);
await page.goto("http://localhost:8787/_admin");
const name = `Twin ${Date.now()}`;
await page.type("#invite input[name=name]", name); await page.click("#invite button"); await page.waitForSelector("#link:not([hidden])");
const dialogs = []; page.on("dialog", (d) => { dialogs.push(d.message()); d.dismiss(); });
await page.type("#invite input[name=name]", name); await page.click("#invite button");
await page.waitForFunction(() => document.getElementById("error").textContent.length > 0);
const shown = await page.$eval("#error", (e) => e.textContent);
console.log(dialogs.length === 1 && dialogs[0].includes("Or is this a different person") ? "PASS" : "FAIL", " duplicate name asks before inviting");
console.log(shown.includes("already has access") ? "PASS" : "FAIL", " declining shows the explanation");
console.log(errors.length === 0 ? "PASS" : "FAIL", " no script errors on the page", errors.join("; "));
await browser.close();
